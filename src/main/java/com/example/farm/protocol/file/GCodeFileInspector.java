package com.example.farm.protocol.file;

import com.example.farm.common.utils.GCodeParser;
import com.example.farm.protocol.model.GCodeFileMetadata;
import org.springframework.stereotype.Component;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.time.Instant;
import java.util.ArrayDeque;
import java.util.ArrayList;
import java.util.Base64;
import java.util.Comparator;
import java.util.Deque;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/** Single-pass, bounded inspection of G-code from either an uploaded or a device-owned file. */
@Component
public class GCodeFileInspector {
    public static final long MAX_FILE_BYTES = 512L * 1024 * 1024;
    private static final int MAX_LINE_BYTES = 64 * 1024;
    private static final int HEAD_CHARS = 256 * 1024;
    private static final int TAIL_CHARS = 1024 * 1024;
    private static final int MAX_LAYERS = 100_000;
    private static final int MAX_IMAGE_CANDIDATES = 8;
    private static final Set<String> SOURCES = Set.of("SERVER_UPLOAD", "MOONRAKER", "RRF", "GCODE_FALLBACK");
    private static final Pattern THUMBNAIL_START = Pattern.compile(
            "(?i)^\\s*;\\s*thumbnail(?:_(?:PNG|JPG|QOI))?\\s+(?:begin|start)\\s+(\\d+)x(\\d+)\\s+(\\d+)\\s*$");
    private static final Pattern THUMBNAIL_END = Pattern.compile(
            "(?i)^\\s*;\\s*thumbnail(?:_(?:PNG|JPG|QOI))?\\s+(?:end|stop)\\s*$");
    private static final Pattern LAYER_CHANGE = Pattern.compile("(?i)^\\s*;\\s*(?:CHANGE_LAYER|LAYER_CHANGE)\\s*$");
    private static final Pattern LAYER_NUMBER = Pattern.compile("(?i)^\\s*;\\s*LAYER\\s*:\\s*(\\d+)\\s*$");
    private static final Pattern LAYER_COMMAND = Pattern.compile(
            "(?i)^\\s*SET_PRINT_STATS_INFO\\b[^;]*?\\bCURRENT_LAYER\\s*=\\s*(\\d+)\\b");
    private static final Pattern SLICER = Pattern.compile(
            "(?im)^\\s*;\\s*generated by\\s+(OrcaSlicer|BambuStudio|PrusaSlicer|SuperSlicer|Cura_SteamEngine)\\s+v?([^\\s;]+)");
    private static final Pattern SETTING = Pattern.compile("(?m)^\\s*;\\s*([^=\\r\\n]+?)\\s*=\\s*([^\\r\\n]*)$");
    private static final Pattern HEIGHT = Pattern.compile(
            "(?im)^\\s*;\\s*(?:max_z_height|object_height|MAXZ)\\s*[:=]\\s*([0-9]+(?:\\.[0-9]+)?)\\s*$");

    public GCodeFileInspection inspect(InputStream input, String filename, long sizeBytes, String source) throws IOException {
        if (input == null || sizeBytes < -1 || sizeBytes > MAX_FILE_BYTES || !SOURCES.contains(source)) {
            throw new IOException("Unsupported G-code inspection input");
        }
        Scan scan = new Scan();
        MessageDigest digest = digest();
        byte[] buffer = new byte[64 * 1024];
        ByteArrayOutputStream line = new ByteArrayOutputStream(256);
        long count = 0;
        long lineStart = 0;
        boolean overflow = false;
        int read;
        while ((read = input.read(buffer)) != -1) {
            if (Thread.currentThread().isInterrupted()) throw new IOException("G-code inspection interrupted");
            count += read;
            if (count > MAX_FILE_BYTES) throw new IOException("G-code exceeds inspection limit");
            digest.update(buffer, 0, read);
            long chunkStart = count - read;
            for (int i = 0; i < read; i++) {
                if (buffer[i] == '\n') {
                    if (!overflow) scan.line(line.toByteArray(), lineStart);
                    else scan.rejectOpenThumbnail();
                    line.reset();
                    overflow = false;
                    lineStart = chunkStart + i + 1;
                } else if (!overflow) {
                    if (line.size() == MAX_LINE_BYTES) {
                        overflow = true;
                        line.reset();
                    } else {
                        line.write(buffer[i]);
                    }
                }
            }
        }
        if (!overflow && line.size() > 0) scan.line(line.toByteArray(), lineStart);
        if (sizeBytes >= 0 && count != sizeBytes) throw new IOException("G-code size changed during inspection");
        String contentHash = HexFormat.of().formatHex(digest.digest());
        String text = scan.metadataText();
        GCodeParser.GCodeMeta parsed = GCodeParser.parseMetadata(text);
        Matcher slicer = SLICER.matcher(text);
        String slicerName = null;
        String slicerVersion = null;
        if (slicer.find()) {
            slicerName = limited(slicer.group(1), 80);
            slicerVersion = limited(slicer.group(2), 80);
        }
        Long estimated = parsed.getEstimatedPrintTimeSeconds() != null && parsed.getEstimatedPrintTimeSeconds() > 0
                && parsed.getEstimatedPrintTimeSeconds() <= 315_576_000
                ? Long.valueOf(parsed.getEstimatedPrintTimeSeconds().longValue()) : explicitZeroTime(text);
        Long totalLayers = parsed.getTotalLayers() == null || parsed.getTotalLayers() > 1_000_000
                ? null : parsed.getTotalLayers().longValue();
        List<GCodeFileInspection.ThumbnailImage> images = scan.images();
        Matcher height = HEIGHT.matcher(text);
        var metadata = new GCodeFileMetadata(1, contentHash, safeBasename(filename), count, contentHash,
                source, Instant.now(), slicerName, slicerVersion, estimated, totalLayers,
                positive(parsed.getLayerHeight()), positive(parsed.getFirstLayerHeight()), positive(parsed.getNozzleSize()),
                height.find() ? bounded(decimal(height.group(1)), 100_000) : null,
                temperature(parsed.getNozzleTemp()), temperature(parsed.getFirstLayerNozzleTemp()),
                temperature(parsed.getBedTemp()), temperature(parsed.getFirstLayerBedTemp()),
                filaments(text, parsed), images.stream().map(GCodeFileInspection.ThumbnailImage::descriptor).toList());
        return new GCodeFileInspection(metadata, images, scan.layers(totalLayers));
    }

    public static String safeBasename(String filename) {
        if (filename == null) return "unnamed.gcode";
        int separator = Math.max(filename.lastIndexOf('/'), filename.lastIndexOf('\\'));
        String name = filename.substring(separator + 1).replaceAll("[:\\p{Cntrl}]", "_");
        if (name.isBlank()) return "unnamed.gcode";
        return name.length() > 128 ? name.substring(0, 128) : name;
    }

    private static Long explicitZeroTime(String text) {
        return Pattern.compile("(?im)^\\s*;?\\s*(?:TIME|estimated_time)\\s*[:=]\\s*0\\s*$").matcher(text).find()
                ? 0L : null;
    }

    private static List<GCodeFileMetadata.Filament> filaments(String text, GCodeParser.GCodeMeta fallback) {
        Map<String, String> settings = new LinkedHashMap<>();
        Matcher matcher = SETTING.matcher(text);
        while (matcher.find()) settings.put(matcher.group(1).trim().toLowerCase(Locale.ROOT), matcher.group(2));
        List<String> materials = values(settings.get("filament_type"));
        List<String> colors = values(settings.getOrDefault("filament_colour", settings.get("filament_color")));
        List<String> lengths = values(settings.get("filament used [mm]"));
        List<String> weights = values(settings.get("filament used [g]"));
        int count = Math.max(Math.max(materials.size(), colors.size()), Math.max(lengths.size(), weights.size()));
        if (count == 0 && (fallback.getMaterialType() != null || fallback.getFilamentUsedMM() != null
                || fallback.getFilamentUsedG() != null)) count = 1;
        List<GCodeFileMetadata.Filament> result = new ArrayList<>();
        for (int i = 0; i < Math.min(count, 8); i++) {
            String material = at(materials, i);
            BigDecimal length = decimal(at(lengths, i));
            BigDecimal weight = decimal(at(weights, i));
            if (i == 0) {
                if (material == null) material = fallback.getMaterialType();
                if (count == 1) {
                    if (length == null) length = fallback.getFilamentUsedMM();
                    if (weight == null) weight = fallback.getFilamentUsedG();
                }
            }
            String color = at(colors, i);
            if (color != null && !color.matches("#[0-9A-Fa-f]{6}(?:[0-9A-Fa-f]{2})?")) color = null;
            result.add(new GCodeFileMetadata.Filament("tool-" + i, limited(material, 80), color,
                    bounded(length, 1_000_000_000), bounded(weight, 1_000_000)));
        }
        return result;
    }

    private static List<String> values(String value) {
        if (value == null || value.isBlank()) return List.of();
        return List.of(value.split("[,;]", -1)).stream().limit(8)
                .map(item -> item.trim().replaceAll("^\"|\"$", "")).toList();
    }

    private static String at(List<String> values, int index) { return index < values.size() ? values.get(index) : null; }
    private static String limited(String value, int length) {
        if (value == null || value.isBlank()) return null;
        String safe = value.replaceAll("\\p{Cntrl}", "_");
        return safe.length() > length ? safe.substring(0, length) : safe;
    }
    private static BigDecimal decimal(String value) {
        if (value == null || !value.matches("[0-9]+(?:\\.[0-9]+)?") || value.length() > 24) return null;
        return new BigDecimal(value);
    }
    private static BigDecimal positive(BigDecimal value) {
        return value != null && value.signum() > 0 ? bounded(value, 10) : null;
    }
    private static BigDecimal bounded(BigDecimal value, long maximum) {
        return value != null && value.signum() >= 0 && value.compareTo(BigDecimal.valueOf(maximum)) <= 0 ? value : null;
    }
    private static Integer temperature(Integer value) {
        return value != null && value >= 0 && value <= 500 ? value : null;
    }
    private static MessageDigest digest() {
        try { return MessageDigest.getInstance("SHA-256"); }
        catch (NoSuchAlgorithmException unavailable) { throw new IllegalStateException(unavailable); }
    }

    private static final class Scan {
        private final StringBuilder head = new StringBuilder();
        private final Deque<String> tail = new ArrayDeque<>();
        private int tailChars;
        private final List<GCodeFileInspection.LayerMark> layerMarks = new ArrayList<>();
        private boolean layerIndexValid = true;
        private long incrementalLayer;
        private final List<GCodeFileInspection.ThumbnailImage> selectedImages = new ArrayList<>();
        private StringBuilder imageData;
        private int imageWidth, imageHeight, declaredLength, imageCandidates;
        private boolean imageValid;

        void line(byte[] bytes, long offset) {
            if (bytes.length == 0) return;
            String line = new String(bytes, StandardCharsets.UTF_8).stripTrailing();
            Matcher begin = THUMBNAIL_START.matcher(line);
            if (begin.matches()) {
                imageData = new StringBuilder();
                imageValid = ++imageCandidates <= MAX_IMAGE_CANDIDATES;
                imageWidth = integer(begin.group(1));
                imageHeight = integer(begin.group(2));
                declaredLength = integer(begin.group(3));
                imageValid &= imageWidth > 0 && imageHeight > 0 && imageWidth <= GCodeThumbnailCodec.MAX_DIMENSION
                        && imageHeight <= GCodeThumbnailCodec.MAX_DIMENSION && declaredLength > 0
                        && declaredLength <= GCodeThumbnailCodec.MAX_INPUT_BYTES * 4L / 3 + 4;
                return;
            }
            if (imageData != null) {
                if (THUMBNAIL_END.matcher(line).matches()) {
                    finishImage();
                    imageData = null;
                } else if (imageValid) {
                    String data = line.stripLeading();
                    if (!data.startsWith(";")) { imageValid = false; return; }
                    data = data.substring(1).trim();
                    if (!data.matches("[A-Za-z0-9+/=]*")
                            || imageData.length() + data.length() > GCodeThumbnailCodec.MAX_INPUT_BYTES * 4L / 3 + 4) {
                        imageValid = false;
                    } else imageData.append(data);
                }
                return;
            }
            if (line.stripLeading().startsWith(";")) sample(line);
            Matcher explicit = LAYER_COMMAND.matcher(line);
            Matcher numbered = LAYER_NUMBER.matcher(line);
            if (explicit.find()) addLayer(offset, positiveLong(explicit.group(1)));
            else if (numbered.matches()) addLayer(offset, positiveLong(numbered.group(1)) + 1);
            else if (LAYER_CHANGE.matcher(line).matches()) addLayer(offset, ++incrementalLayer);
        }

        void rejectOpenThumbnail() { imageValid = false; }

        private void sample(String line) {
            String value = line + '\n';
            if (head.length() + value.length() <= HEAD_CHARS) head.append(value);
            tail.addLast(value);
            tailChars += value.length();
            while (tailChars > TAIL_CHARS && !tail.isEmpty()) tailChars -= tail.removeFirst().length();
        }

        String metadataText() { return head + "\n" + String.join("", tail); }

        private void addLayer(long offset, long layer) {
            if (!layerIndexValid) return;
            if (layer < 0 || layerMarks.size() >= MAX_LAYERS
                    || (!layerMarks.isEmpty() && layer < layerMarks.getLast().layer())) {
                layerIndexValid = false;
                layerMarks.clear();
                return;
            }
            incrementalLayer = layer;
            if (layerMarks.isEmpty() || layer != layerMarks.getLast().layer()) {
                layerMarks.add(new GCodeFileInspection.LayerMark(offset, layer));
            }
        }

        List<GCodeFileInspection.LayerMark> layers(Long total) {
            if (!layerIndexValid || (total != null && !layerMarks.isEmpty() && layerMarks.getLast().layer() > total)) {
                return List.of();
            }
            return List.copyOf(layerMarks);
        }

        private void finishImage() {
            if (!imageValid) return;
            try {
                byte[] raw = Base64.getDecoder().decode(imageData.toString());
                if (declaredLength != imageData.length() && declaredLength != raw.length) return;
                var image = GCodeThumbnailCodec.normalize(raw);
                if (image.descriptor().width() != imageWidth || image.descriptor().height() != imageHeight) return;
                if (selectedImages.stream().anyMatch(existing -> existing.descriptor().sha256().equals(image.descriptor().sha256()))) return;
                selectedImages.add(image);
                selectedImages.sort(Comparator.comparingInt(value -> value.descriptor().width() * value.descriptor().height()));
                if (selectedImages.size() > 2) selectedImages.remove(1);
            } catch (IOException | IllegalArgumentException invalid) {
                // A malformed preview does not invalidate independent slicing metadata.
            }
        }

        List<GCodeFileInspection.ThumbnailImage> images() { return List.copyOf(selectedImages); }
        private static int integer(String value) {
            try { return Integer.parseInt(value); } catch (NumberFormatException invalid) { return -1; }
        }
        private static long positiveLong(String value) {
            try { return Long.parseLong(value); } catch (NumberFormatException invalid) { return -1; }
        }
    }
}
