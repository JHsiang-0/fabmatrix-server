package com.example.farm.protocol.file;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.example.farm.protocol.model.GCodeFileMetadata;
import org.junit.jupiter.api.Test;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.Base64;
import java.util.List;
import java.time.Instant;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class GCodeFileInspectorTest {
    private final GCodeFileInspector inspector = new GCodeFileInspector();

    @Test
    void inspectsOrcaMetadataAndBothCompletePreviewsIncludingShortBase64Tail() throws Exception {
        byte[] small = png(48, 48);
        byte[] large = png(300, 300);
        String text = "; generated by OrcaSlicer 2.3.1 on 2026-11-01\n"
                + "; total layer number: 20\n"
                + "; model printing time: 1h 2m; total estimated time: 1h 5m 3s\n"
                + thumbnail(small, 48, 48, "thumbnail_PNG")
                + "; metadata padding\n".repeat(1000)
                + thumbnail(large, 300, 300, "thumbnail")
                + "; filament_type = \"PLA\";\"PETG\"\n"
                + "; filament_colour = #FF0000;#00FF00\n"
                + "; filament used [mm] = 1500,2500\n"
                + "; filament used [g] = 4.5,6.5\n"
                + "; nozzle_diameter = 0.4\n; layer_height = 0.2\n; first_layer_height = 0.25\n";
        GCodeFileInspection result = inspect(text, "C:\\private\\jobs\\sample.gcode");
        assertThat(result.metadata().fileName()).isEqualTo("sample.gcode");
        assertThat(result.metadata().slicerName()).isEqualTo("OrcaSlicer");
        assertThat(result.metadata().slicerVersion()).isEqualTo("2.3.1");
        assertThat(result.metadata().estimatedPrintSeconds()).isEqualTo(3903);
        assertThat(result.metadata().totalLayers()).isEqualTo(20);
        assertThat(result.metadata().nozzleDiameterMm()).isEqualByComparingTo("0.4");
        assertThat(result.metadata().filaments()).hasSize(2);
        assertThat(result.metadata().filaments().get(1).material()).isEqualTo("PETG");
        assertThat(result.metadata().filaments().get(1).lengthMm()).isEqualByComparingTo("2500");
        assertThat(result.metadata().filaments().get(0).weightGrams()).isEqualByComparingTo("4.5");
        assertThat(result.metadata().thumbnails()).extracting(value -> value.width()).containsExactly(48, 300);
        assertThat(result.thumbnails()).hasSize(2);
        for (var image : result.thumbnails()) {
            assertThat(image.descriptor().sizeBytes()).isEqualTo(image.png().length);
            assertThat(image.descriptor().sha256()).isEqualTo(GCodeThumbnailCodec.sha256(image.png()));
            assertThat(ImageIO.read(new ByteArrayInputStream(image.png()))).isNotNull();
        }
        assertThat(new ObjectMapper().findAndRegisterModules().writeValueAsString(result.metadata()))
                .doesNotContain("private", "C:", "base64");
    }

    @Test
    void preservesRawByteOffsetsForUtf8AndCrLfAndExposesDerivedLayerIndex() throws Exception {
        String beginning = "; 文件名测试\r\n; total layer number: 2\r\nG28\r\n";
        String first = "; CHANGE_LAYER\r\nG1 Z0.2\r\n";
        String second = "; CHANGE_LAYER\r\nG1 Z0.4\r\n";
        GCodeFileInspection result = inspect(beginning + first + second, "test.gcode");
        int firstOffset = beginning.getBytes(StandardCharsets.UTF_8).length;
        int secondOffset = (beginning + first).getBytes(StandardCharsets.UTF_8).length;
        assertThat(result.layers()).containsExactly(new GCodeFileInspection.LayerMark(firstOffset, 1),
                new GCodeFileInspection.LayerMark(secondOffset, 2));
        assertThat(result.currentLayerAt(0)).isNull();
        assertThat(result.currentLayerAt(firstOffset - 1)).isNull();
        assertThat(result.currentLayerAt(firstOffset)).isEqualTo(1);
        assertThat(result.currentLayerAt(secondOffset)).isEqualTo(2);
        assertThat(result.currentLayerAt(result.metadata().sizeBytes() + 1)).isNull();
    }

    @Test
    void dropsNonMonotonicAndOutOfRangeLayerIndices() throws Exception {
        assertThat(inspect("; LAYER:0\nG1\n; LAYER:1\nG1\n; LAYER:0\n", "test.gcode").layers()).isEmpty();
        assertThat(inspect("; total layer number: 1\n; CHANGE_LAYER\n; CHANGE_LAYER\n", "test.gcode").layers()).isEmpty();
    }

    @Test
    void unknownSlicingValuesRemainNullAndContentIdentityIsStable() throws Exception {
        GCodeFileInspection result = inspect("G28\nG1 X1\n", "test.gcode");
        assertThat(result.metadata().estimatedPrintSeconds()).isNull();
        assertThat(result.metadata().totalLayers()).isNull();
        assertThat(result.metadata().filaments()).isEmpty();
        assertThat(result.metadata().nozzleDiameterMm()).isNull();
        assertThat(result.metadata().sha256()).hasSize(64).isEqualTo(result.metadata().fileId());
        assertThat(inspect("G28\nG1 X1\n", "renamed.gcode").metadata().fileId()).isEqualTo(result.metadata().fileId());
        assertThat(inspect("; TIME:0\n", "zero.gcode").metadata().estimatedPrintSeconds()).isZero();
    }

    @Test
    void doesNotAssignAnAggregateMaterialWeightToTheFirstOfSeveralTools() throws Exception {
        var result = inspect("; filament_type = PLA;PETG\n; total filament used [g] = 10\n", "test.gcode");
        assertThat(result.metadata().filaments()).hasSize(2);
        assertThat(result.metadata().filaments()).allMatch(value -> value.weightGrams() == null);
        var invalid = inspect("; layer_height = 0\n; nozzle_diameter = 999\n; nozzle_temperature = 9000\n", "test.gcode");
        assertThat(invalid.metadata().layerHeightMm()).isNull();
        assertThat(invalid.metadata().nozzleDiameterMm()).isNull();
        assertThat(invalid.metadata().nozzleTemperatureC()).isNull();
    }

    @Test
    void skipsIncompleteOrMisdeclaredPreviewWithoutReturningPartialImage() throws Exception {
        String valid = thumbnail(png(5, 5), 5, 5, "thumbnail");
        assertThat(inspect(valid.replace("; thumbnail end\n", ""), "test.gcode").thumbnails()).isEmpty();
        assertThat(inspect(valid.replace("5x5 ", "5x5 99"), "test.gcode").thumbnails()).isEmpty();
        assertThat(inspect(valid.replace("5x5", "6x6"), "test.gcode").thumbnails()).isEmpty();
    }

    @Test
    void checksInputSizeAndReleasesInternalCollectionsFromCallerMutation() throws Exception {
        byte[] bytes = "G28\n".getBytes(StandardCharsets.UTF_8);
        assertThatThrownBy(() -> inspector.inspect(new ByteArrayInputStream(bytes), "test.gcode", 5, "SERVER_UPLOAD"))
                .isInstanceOf(IOException.class).hasMessageContaining("size changed");
        assertThatThrownBy(() -> inspector.inspect(new ByteArrayInputStream(bytes), "test.gcode",
                GCodeFileInspector.MAX_FILE_BYTES + 1, "SERVER_UPLOAD")).isInstanceOf(IOException.class);
        GCodeFileInspection result = inspect(thumbnail(png(5, 5), 5, 5, "thumbnail"), "test.gcode");
        byte[] copy = result.thumbnails().getFirst().png();
        copy[0] = 0;
        assertThat(result.thumbnails().getFirst().png()[0]).isEqualTo((byte) 0x89);
        assertThatThrownBy(() -> result.thumbnails().clear()).isInstanceOf(UnsupportedOperationException.class);
        assertThat(new ObjectMapper().findAndRegisterModules().writeValueAsString(result)).doesNotContain("\"png\"");
        var nullSize = new GCodeFileMetadata(1, "file", "file.gcode", null, null,
                "RRF", Instant.now(), null, null, null, null, null, null, null, null,
                null, null, null, null, List.of(), List.of());
        assertThat(new GCodeFileInspection(nullSize, List.of(), List.of(new GCodeFileInspection.LayerMark(1, 1)))
                .currentLayerAt(2)).isNull();
    }

    private GCodeFileInspection inspect(String text, String filename) throws IOException {
        byte[] bytes = text.getBytes(StandardCharsets.UTF_8);
        return inspector.inspect(new ByteArrayInputStream(bytes), filename, bytes.length, "SERVER_UPLOAD");
    }

    static String thumbnail(byte[] image, int width, int height, String tag) {
        String base64 = Base64.getEncoder().encodeToString(image);
        StringBuilder result = new StringBuilder("; " + tag + " begin " + width + "x" + height + " " + base64.length() + "\n");
        for (int offset = 0; offset < base64.length(); offset += 73) {
            result.append("; ").append(base64, offset, Math.min(offset + 73, base64.length())).append('\n');
        }
        return result.append("; ").append(tag).append(" end\n").toString();
    }

    static byte[] png(int width, int height) throws IOException {
        BufferedImage image = new BufferedImage(width, height, BufferedImage.TYPE_INT_RGB);
        for (int y = 0; y < height; y++) {
            for (int x = 0; x < width; x++) image.setRGB(x, y, (x * 4747 + y * 7919) & 0xFFFFFF);
        }
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        ImageIO.write(image, "PNG", bytes);
        return bytes.toByteArray();
    }
}
