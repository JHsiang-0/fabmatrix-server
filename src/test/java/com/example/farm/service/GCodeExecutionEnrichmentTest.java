package com.example.farm.service;

import com.example.farm.entity.Printer;
import com.example.farm.entity.PrinterExecution;
import com.example.farm.protocol.file.GCodeFileInspection;
import com.example.farm.protocol.file.GCodeFileInspector;
import com.example.farm.protocol.model.CanonicalPrinterModel;
import com.example.farm.protocol.model.CanonicalPrinterModelMapper;
import com.example.farm.protocol.model.CanonicalPrinterModelValidator;
import com.example.farm.protocol.observation.PrinterObservationParser;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.Test;

import java.io.ByteArrayInputStream;
import java.nio.charset.StandardCharsets;
import java.time.Instant;
import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

class GCodeExecutionEnrichmentTest {
    @Test void supplementsMissingFileFieldsAndMarksEveryDerivedRuntimeValue() throws Exception {
        var inspection = inspection();
        var original = model(inspection, "null", "null", 100);
        var enriched = GCodeExecutionEnrichment.apply(original, inspection);
        var execution = enriched.observation().currentExecution();
        assertEquals(1200, execution.timing().slicerEstimatedTotalSeconds().value().intValueExact());
        assertEquals(CanonicalPrinterModel.MeasurementSource.SLICER_ESTIMATE, execution.timing().slicerEstimatedTotalSeconds().source());
        assertEquals(2L, execution.layers().total().value());
        assertEquals(2L, execution.layers().current().value());
        assertEquals(CanonicalPrinterModel.MeasurementSource.SERVER_DERIVED, execution.layers().current().source());
        assertEquals(1100, execution.estimatedRemaining().seconds().value().intValueExact());
        assertEquals(CanonicalPrinterModel.RemainingMethod.SERVER_MODEL, execution.estimatedRemaining().method());
        assertEquals(inspection.metadata().sha256(), execution.file().sha256());
        assertEquals(original.observation().observedAt(), enriched.observation().observedAt());
        assertEquals(CanonicalPrinterModel.SupportState.SUPPORTED, enriched.descriptor().capabilities().stream()
                .filter(capability -> "READ_LAYER_PROGRESS".equals(capability.code())).findFirst().orElseThrow().support());
        assertEquals(CanonicalPrinterModel.SupportState.SUPPORTED, enriched.descriptor().capabilities().stream()
                .filter(capability -> "READ_REMAINING_TIME".equals(capability.code())).findFirst().orElseThrow().support());
        CanonicalPrinterModelValidator.validate(enriched);
    }

    @Test void retainsDeviceLayerReportsAndDoesNotPretendAnOverduePrintHasZeroRemaining() throws Exception {
        var inspection = inspection();
        var original = model(inspection, "1", "2", 1500);
        var execution = GCodeExecutionEnrichment.apply(original, inspection).observation().currentExecution();
        assertEquals(original.observation().currentExecution().layers().current(), execution.layers().current());
        assertNull(execution.estimatedRemaining().seconds().value());
    }

    private GCodeFileInspection inspection() throws Exception {
        byte[] bytes = ("; generated by OrcaSlicer 2.3.0\n; estimated printing time (normal mode) = 20m\n"
                + "; total layer number: 2\n;CHANGE_LAYER\nG1 Z0.2\n;CHANGE_LAYER\nG1 Z0.4\n").getBytes(StandardCharsets.UTF_8);
        return new GCodeFileInspector().inspect(new ByteArrayInputStream(bytes), "model.gcode", bytes.length, "SERVER_UPLOAD");
    }

    private CanonicalPrinterModel model(GCodeFileInspection inspection, String current, String total, int elapsed) throws Exception {
        Instant at = Instant.parse("2026-11-07T04:00:00Z");
        var printer = new Printer();
        printer.setId(1L);
        printer.setDeviceUid(UUID.randomUUID().toString());
        printer.setFirmwareType("KLIPPER");
        printer.setName("Fixture printer");
        printer.setMonitorEnabled(true);
        var execution = new PrinterExecution();
        execution.setExecutionUid(UUID.randomUUID().toString());
        execution.setSource("EXTERNAL");
        execution.setState("ACTIVE");
        execution.setFirstObservedAt(LocalDateTime.ofInstant(at, ZoneId.systemDefault()));
        String json = """
                {"webhooks":{"state":"ready"},"display_status":{"progress":0.5},
                 "print_stats":{"state":"printing","filename":"model.gcode","print_duration":%d,"total_duration":%d,
                   "info":{"current_layer":%s,"total_layer":%s}},
                 "virtual_sdcard":{"file_position":%d,"file_size":%d}}
                """.formatted(elapsed, elapsed, current, total, inspection.metadata().sizeBytes(), inspection.metadata().sizeBytes());
        var observation = PrinterObservationParser.klipper(new ObjectMapper().readTree(json), at, at);
        return CanonicalPrinterModelMapper.map(printer, UUID.randomUUID(), UUID.randomUUID(), 1, 1,
                observation, execution, false, at);
    }
}
