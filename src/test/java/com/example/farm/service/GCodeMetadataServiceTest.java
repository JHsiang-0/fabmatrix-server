class GCodeMetadataServiceTest {
    private final GCodeMetadataStore store = mock(GCodeMetadataStore.class);
    private final PrinterFileMetadataReader reader = mock(PrinterFileMetadataReader.class);
    private final PrinterMapper printers = mock(PrinterMapper.class);
    private final PrinterExecutionMapper executions = mock(PrinterExecutionMapper.class);
    private final FileStorage files = mock(FileStorage.class);
    private final PrintFileMapper printFiles = mock(PrintFileMapper.class);
    private GCodeMetadataService service;
    private GCodeFileInspection inspection;
    private CanonicalPrinterModel model;
    private Printer printer;
    private PrinterExecution execution;

    @BeforeEach void setup() throws Exception {
        byte[] bytes = ("; generated by OrcaSlicer 2.3.0\n; estimated printing time (normal mode) = 20m\n"
                + "; total layer number: 2\n;CHANGE_LAYER\nG1 Z0.2\n;CHANGE_LAYER\nG1 Z0.4\n").getBytes(StandardCharsets.UTF_8);
        inspection = new GCodeFileInspector().inspect(new ByteArrayInputStream(bytes), "model.gcode", bytes.length, "GCODE_FALLBACK");
        printer = new Printer();
        printer.setId(1L);
        printer.setName("Isolated printer");
        printer.setDeviceUid(UUID.randomUUID().toString());
        printer.setFirmwareType("KLIPPER");
        printer.setIpAddress("127.0.0.1");
        printer.setMonitorEnabled(true);
        execution = new PrinterExecution();
        execution.setPrinterId(1L);
        execution.setExecutionUid(UUID.randomUUID().toString());
        execution.setSource("EXTERNAL");
        execution.setState("ACTIVE");
        execution.setObservedFilename("model.gcode");
        Instant at = Instant.now();
        execution.setFirstObservedAt(LocalDateTime.ofInstant(at, ZoneId.systemDefault()));
        var observation = PrinterObservationParser.klipper(new ObjectMapper().readTree("""
                {"webhooks":{"state":"ready"},"display_status":{"progress":0.5},
                 "print_stats":{"state":"printing","filename":"model.gcode","print_duration":100,"total_duration":100},
                 "virtual_sdcard":{"file_position":%d,"file_size":%d}}
                """.formatted(bytes.length, bytes.length)), at, at);
        model = CanonicalPrinterModelMapper.map(printer, UUID.randomUUID(), UUID.randomUUID(), 1, 1, observation, execution, false, at);
        when(printers.selectById(1L)).thenReturn(printer);
        when(executions.selectOne(any())).thenReturn(execution);
        service = new GCodeMetadataService(store, new GCodeFileInspector(), reader, files, printers,
                executions, mock(PrintJobMapper.class), printFiles);
    }

    @AfterEach void stop() { service.close(); }

    @Test void coldCacheDatabaseReadRunsOnTheWorkerAndThenEnrichesWithoutAnyDeviceRequest() throws Exception {
        var readThread = new AtomicReference<Thread>();
        var seen = new CountDownLatch(1);
        when(store.find(anyString())).thenAnswer(invocation -> {
            readThread.set(Thread.currentThread());
            seen.countDown();
            return new GCodeMetadataStore.Entry("execution:" + execution.getExecutionUid(), 1L,
                    execution.getExecutionUid(), printer.getDeviceUid(), "model.gcode", inspection);
        });
        assertSame(model, service.enrich(printer, execution, "model.gcode", model));
        assertTrue(seen.await(5, TimeUnit.SECONDS));
        assertNotSame(Thread.currentThread(), readThread.get());
        CanonicalPrinterModel result = model;
        long deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(5);
        while (result == model && System.nanoTime() < deadline) {
            Thread.sleep(5);
            result = service.enrich(printer, execution, "model.gcode", model);
        }
        assertEquals(1200, result.observation().currentExecution().timing().slicerEstimatedTotalSeconds().value().intValueExact());
        verify(reader, never()).read(any(), anyString(), anyBoolean());
    }

    @Test void externalFileReadFinishingAfterExecutionEndsCannotBeAttachedToThatOldExecution() throws Exception {
        assertDiscardedAfterRead(() -> execution.setState("COMPLETED"));
    }

    @Test void endpointChangeDuringExternalReadDiscardsTheResponse() throws Exception {
        assertDiscardedAfterRead(() -> printer.setIpAddress("127.0.0.2"));
    }

    @Test void uploadedPngIsPromotedToTheExistingLocalFilePreviewAfterParsing() throws Exception {
        uploadFixture(1);
        verify(store, org.mockito.Mockito.timeout(5000)).save(any());
        verify(files).uploadBytes(anyString(), any(byte[].class), org.mockito.ArgumentMatchers.eq("image/png"));
        verify(files).deleteFileByObjectUrl("old-preview");
        verify(files, never()).deleteFile(anyString());
    }

    @Test void concurrentFileDeletionCleansTheNewPreviewObject() throws Exception {
        uploadFixture(0);
        verify(files, org.mockito.Mockito.timeout(5000)).deleteFile(anyString());
        verify(files, never()).deleteFileByObjectUrl(anyString());
    }

    private void uploadFixture(int updated) throws Exception {
        var png = new ByteArrayOutputStream();
        ImageIO.write(new BufferedImage(2, 2, BufferedImage.TYPE_INT_RGB), "png", png);
        String encoded = Base64.getEncoder().encodeToString(png.toByteArray());
        byte[] gcode = ("; generated by OrcaSlicer 2.3.0\n; thumbnail begin 2x2 " + encoded.length()
                + "\n; " + encoded + "\n; thumbnail end\nG1 X1\n").getBytes(StandardCharsets.UTF_8);
        var file = new PrintFile();
        file.setId(5L);
        file.setSafeName("safe.gcode");
        file.setOriginalName("model.gcode");
        file.setFileSize((long) gcode.length);
        file.setThumbnailUrl("old-preview");
        when(printFiles.selectById(5L)).thenReturn(file);
        when(files.getFileStream("safe.gcode")).thenReturn(new InputStreamResource(new ByteArrayInputStream(gcode)));
        when(files.uploadBytes(anyString(), any(byte[].class), anyString())).thenReturn("new-preview");
        when(printFiles.update(org.mockito.ArgumentMatchers.<PrintFile>isNull(), any())).thenReturn(updated);
        service.uploaded(file);
    }

    private void assertDiscardedAfterRead(Runnable change) throws Exception {
        var reading = new CountDownLatch(1);
        var release = new CountDownLatch(1);
        var reads = new AtomicInteger();
        var checked = new CountDownLatch(1);
        when(executions.selectOne(any())).thenAnswer(invocation -> {
            if (reads.incrementAndGet() >= 2) checked.countDown();
            return execution;
        });
        when(reader.read(any(), anyString(), anyBoolean())).thenAnswer(invocation -> {
            reading.countDown();
            if (!release.await(5, TimeUnit.SECONDS)) throw new IllegalStateException("Fixture release missing");
            return inspection;
        });
        try {
            assertSame(model, service.enrich(printer, execution, "model.gcode", model));
            assertTrue(reading.await(5, TimeUnit.SECONDS));
            change.run();
            release.countDown();
            assertTrue(checked.await(5, TimeUnit.SECONDS));
            verify(store, after(200).never()).save(any());
        } finally { release.countDown(); }
    }
}
